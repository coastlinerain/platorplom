pub struct Map {
    pub grids: Vec<Vec<Vec<Vec<TileType>>>>,
    pub data: Vec<Vec<Vec<Vec<EntityType>>>>,
}

impl Map {
    pub fn new() -> Self {
        let grids = Self::get_world_matrix();
        let data = Self::get_world_data();
        Self { grids, data }
    }

    fn get_world_matrix() -> Vec<Vec<Vec<Vec<TileType>>>> {
        // Internal helper to avoid repeating code
        fn convert(raw_layout: [[u8; MAP_WIDTH]; MAP_HEIGHT]) -> Vec<Vec<TileType>> {
            raw_layout
                .iter()
                .map(|row| {
                    row.iter()
                        .map(|&value| TileType::from(value)) // Convert u8 to TileType
                        .collect()
                })
                .collect()
        }

        let row0 = vec![convert(LVL_0_0), convert(LVL_0_1)];
        let row1 = vec![convert(LVL_1_0), convert(LVL_1_1)];

        vec![row0, row1]
    }

    fn get_world_data() -> Vec<Vec<Vec<Vec<EntityType>>>> {
        // Internal helper to avoid repeating code
        fn convert(raw_layout: [[u8; MAP_WIDTH]; MAP_HEIGHT]) -> Vec<Vec<EntityType>> {
            raw_layout
                .iter()
                .map(|row| {
                    row.iter()
                        .map(|&value| EntityType::from(value)) // Convert u8 to EntityType
                        .collect()
                })
                .collect()
        }

        let row0 = vec![convert(DATA_0_0), convert(DATA_0_1)];
        let row1 = vec![convert(DATA_1_0), convert(DATA_1_1)];

        vec![row0, row1]
    }
}

impl Default for Map {
    fn default() -> Self {
        Self::new()
    }
}

#[cfg(test)]
mod tests {
    use super::Map;
    use crate::config::{MAP_HEIGHT, MAP_WIDTH};
    use crate::types::{EntityType, TileType};

    #[test]
    fn map_new_shape() {
        let map = Map::new();

        assert_eq!(map.grids.len(), 2);
        for row in &map.grids {
            assert_eq!(row.len(), 2);
            for grid in row {
                assert_eq!(grid.len(), MAP_HEIGHT);
                for inner_row in grid {
                    assert_eq!(inner_row.len(), MAP_WIDTH);
                }
            }
        }

        assert_eq!(map.data.len(), 2);
        for row in &map.data {
            assert_eq!(row.len(), 2);
            for grid in row {
                assert_eq!(grid.len(), MAP_HEIGHT);
                for inner_row in grid {
                    assert_eq!(inner_row.len(), MAP_WIDTH);
                }
            }
        }
    }

    #[test]
    fn map_new_conversion_spot_checks() {
        let map = Map::new();

        assert_eq!(map.grids[0][0][0][0], TileType::Wall);
        assert_eq!(map.grids[0][0][1][1], TileType::Empty);
        assert_eq!(map.data[0][0][0][0], EntityType::Empty);
    }
}
